export const MESSAGES: Record<Lang, Dict> = { pt, en, es };

/** Lê uma chave no idioma pedido, caindo para o português; interpola {var}. */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let text = MESSAGES[lang][key] ?? MESSAGES.pt[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return text;
}
